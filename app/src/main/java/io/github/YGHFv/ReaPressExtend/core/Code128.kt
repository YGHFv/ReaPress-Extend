package io.github.YGHFv.ReaPressExtend.core

/**
 * Code 128-B 条码编码器 —— 身份码弹窗里那根条码是模块自己画的。
 *
 * ## 为什么要自己写
 *
 * 菜鸟的身份码页面上是一根条码（宿主里带了 zxing，`com.google.zxing.oned.Code128Writer` 确实存在），
 * 但那套 API 只存在于**宿主进程**：模块 APK 里没有 zxing，也不能为了一根条码把整个 zxing 引进来
 * （项目一贯的取舍：不引第三套图形/编码栈）。Code 128-B 的规格本身是**固定的常量表 + 一个
 * 加权取模校验**，几十行就写完了，而且它是纯函数、可以用已知向量钉死。
 *
 * ## 只支持 B 组
 *
 * 身份码是数字（可能带字母），B 组覆盖全部可打印 ASCII（32..126），A 组（控制字符）与 C 组
 * （数字对压缩）在这里没有收益 —— 少两个组就少两套转移规则和两倍出错面。
 *
 * ## 输出是「模块宽度序列」而不是位图
 *
 * 返回值从**条**开始，条/空交替。画的时候第 0、2、4…项是黑条，1、3、5…项是空白 ——
 * 具体画多高、多宽由 UI 决定（这里只给相对宽度）。这样它留在 core 层、不碰 Canvas，
 * 也就能单测。
 */
object Code128 {

    /**
     * 107 个符号的模块宽度表（索引即符号值），每项 6 位；[STOP]（106 号）是 7 位。
     *
     * 这是 Code 128 规格里的固定表，不是我们编的。逐位比对过三处独立来源（zxing
     * `Code128Reader.CODE_PATTERNS`、barcodesinc 的 Code 128 字符集表、以及几份中文规格表），
     * 100..106 段完全一致；`ExpressIdentityTest` 另用「Start B / 已知校验和 / Stop」三段钉住。
     *
     * 表本身有两条不用查资料就能自检的不变量（单测里跑着）：
     * - 每项模块宽度**相加恒为 11**（[STOP] 是 13）—— 抄错一位数字当场暴露；
     * - 107 项图案**两两不同** —— 抄重一项当场暴露。
     *
     * 这两条是必须留的：表抄错了条码在屏幕上看不出任何异常（该黑的黑、该白的白），
     * 只有用户在自助机前扫不出来 —— 那是最糟的失败形态。
     */
    private val PATTERNS = listOf(
        "212222", "222122", "222221", "121223", "121322", "131222", "122213", "122312",
        "132212", "221213", "221312", "231212", "112232", "122132", "122231", "113222",
        "123122", "123221", "223211", "221132", "221231", "213212", "223112", "312131",
        "311222", "321122", "321221", "312212", "322112", "322211", "212123", "212321",
        "232121", "111323", "131123", "131321", "112313", "132113", "132311", "211313",
        "231113", "231311", "112133", "112331", "132131", "113123", "113321", "133121",
        "313121", "211331", "231131", "213113", "213311", "213131", "311123", "311321",
        "331121", "312113", "312311", "332111", "314111", "221411", "431111", "111224",
        "111422", "121124", "121421", "141122", "141221", "112214", "112412", "122114",
        "122411", "142112", "142211", "241211", "221114", "413111", "241112", "134111",
        "111242", "121142", "121241", "114212", "124112", "124211", "411212", "421112",
        "421211", "212141", "214121", "412121", "111143", "111341", "131141", "114113",
        "114311", "411113", "411311", "113141", "114131", "311141", "411131", "211412",
        "211214", "211232", "2331112",
    )

    /** Start B（进入 B 组的起始符）。 */
    private const val START_B = 104

    /** Stop（终止符，7 位 —— 表里唯一一个不是 6 位的）。 */
    private const val STOP = 106

    /** 校验和模数。 */
    private const val CHECK_MOD = 103

    /** B 组可编码的最小 / 最大 ASCII 码。 */
    private const val MIN_ASCII = 32
    private const val MAX_ASCII = 126

    /**
     * 编码一段文本。
     *
     * @return 模块宽度序列（以**条**开始，条/空交替）；文本为空、或含 B 组编不了的字符时返回 null。
     *
     * 不做「自动降级到 A/C 组」：身份码是可见字符，编码失败只有两种可能 —— 拿到的码是脏数据，
     * 或者我们这张表错了。两种都该**显示数字、不显示条码**，而不是硬编一根扫不出来的条码。
     */
    fun encodeB(text: String): List<Int>? {
        if (text.isEmpty()) return null

        val symbols = ArrayList<Int>(text.length + 3)
        symbols += START_B
        for (ch in text) {
            val code = ch.code
            if (code < MIN_ASCII || code > MAX_ASCII) return null
            // B 组的值 = ASCII - 32（0..94）。这是规格定义，不是偏移量的巧合。
            symbols += code - MIN_ASCII
        }
        symbols += checksum(symbols)
        symbols += STOP

        val widths = ArrayList<Int>(symbols.size * 6 + 1)
        for (symbol in symbols) {
            for (digit in PATTERNS[symbol]) widths += digit - '0'
        }
        return widths
    }

    /**
     * 校验和：起始符**不乘位置**，之后第 i 个数据符号（从 1 开始数）乘以 i，最后对 103 取模。
     *
     * 位置从 1 开始这件事很容易写成 0 —— 那样条码看着完全正常，只是扫不出来。
     */
    private fun checksum(symbols: List<Int>): Int {
        var sum = symbols.first()
        for (index in 1 until symbols.size) {
            sum += symbols[index] * index
        }
        return sum % CHECK_MOD
    }
}
